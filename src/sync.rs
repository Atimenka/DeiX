//! Вспомогательная функция для безопасного доступа к структурам, которые
//! используются и обычным кодом ядра, и обработчиками прерываний (IDT).
//!
//! На однопроцессорной системе спинлок сам по себе НЕ защищает от гонки
//! с обработчиком прерывания: если IRQ срабатывает ровно в момент, когда
//! обычный код держит лок, обработчик прерывания начинает крутиться в
//! ожидании этого же лока — а освободить его некому, поток-владелец
//! "заморожен" на время работы обработчика. Получается мёртвая петля
//! (deadlock), которая выглядит как мгновенное зависание системы.
//!
//! Обработчики прерываний у нас используют "interrupt gate" (не "trap
//! gate"), поэтому процессор сам сбрасывает флаг IF на время их работы —
//! то есть внутри самого обработчика прерывания повторно не сработают.
//! А значит достаточно на время работы с общими данными из ОБЫЧНОГО кода
//! отключать прерывания (cli), чтобы обработчик гарантированно не мог
//! вклиниться в критическую секцию.

use core::arch::asm;

pub fn without_interrupts<F: FnOnce() -> R, R>(f: F) -> R {
    // Сохраняем текущее состояние флага IF (9-й бит regsiter FLAGS), чтобы
    // корректно обрабатывать вложенные вызовы: если прерывания уже были
    // отключены снаружи, не нужно их включать по завершении.
    let saved_flags: u64;
    unsafe {
        asm!(
            "pushfq",
            "pop {}",
            out(reg) saved_flags,
            options(nomem, preserves_flags)
        );
        asm!("cli", options(nomem, nostack));
    }

    let result = f();

    const IF_BIT: u64 = 1 << 9;
    if saved_flags & IF_BIT != 0 {
        unsafe { asm!("sti", options(nomem, nostack)) };
    }

    result
}
