//! Перевод символов кириллицы (Unicode) в коды CP866, под которые мы
//! дозагрузили битмапы в VGA-шрифт (см. font.rs / font_cyrillic.rs).

/// Возвращает код CP866 для данного Unicode-символа, если это одна из
/// кириллических букв, для которых мы сгенерировали глиф. Иначе — None
/// (вызывающий код сам решает, чем заменить символ, например placeholder'ом).
pub fn unicode_to_cp866(ch: char) -> Option<u8> {
    match ch {
        // А-Я (0x0410-0x042F) -> 0x80-0x9F
        'А'..='Я' => Some(0x80 + (ch as u32 - 'А' as u32) as u8),
        // а-п (0x0430-0x043F) -> 0xA0-0xAF
        'а'..='п' => Some(0xA0 + (ch as u32 - 'а' as u32) as u8),
        // р-я (0x0440-0x044F) -> 0xE0-0xEF
        'р'..='я' => Some(0xE0 + (ch as u32 - 'р' as u32) as u8),
        'Ё' => Some(0xF0),
        'ё' => Some(0xF1),
        _ => None,
    }
}
